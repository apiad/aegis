"""``srv.ops``: every registered operation as a keyword-only method.

``srv.ops.<namespace>.<rest>(**params)`` runs the operation named
``<namespace>.<rest>``, with the dots of the rest joined by underscores
(``workflow.edit.apply`` is ``srv.ops.workflow.edit_apply``); an operation
with no dot (``meta``, ``toast``) is a method of ``srv.ops`` itself. The parameters
are validated by the operation's own model, so a wrong one raises the
OpError("bad_params") the websocket gets. The signatures live in
``ops.pyi``, generated by ``make ops-stubs`` (stubs.py); a test keeps it in
step with the registry.
"""

from __future__ import annotations

import keyword
from collections.abc import Awaitable, Callable
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from ..server import Server


def attr_name(op: str) -> tuple[str, str]:
    """The namespace and the method name operation ``op`` gets; a Python
    keyword gets a trailing underscore (``knowledge.import`` is
    ``srv.ops.knowledge.import_``)."""
    ns, _, rest = op.partition(".")
    name = rest.replace(".", "_")
    return ns, f"{name}_" if keyword.iskeyword(name) else name


class Ops:
    def __init__(self, server: Server) -> None:
        self._srv = server
        self._names: dict[str, dict[str, str]] = {}
        for op in server.app.registry.names():
            ns, name = attr_name(op)
            self._names.setdefault(ns, {})[name] = op

    def __getattr__(self, ns: str) -> Any:
        names = self._names.get(ns) if not ns.startswith("_") else None
        if names is None:
            raise AttributeError(f"no operations in namespace {ns!r}")
        if "" in names:
            return _method(self._srv, names[""])
        return Namespace(self._srv, ns, names)

    def __dir__(self) -> list[str]:
        return sorted(self._names)


class Namespace:
    def __init__(self, server: Server, ns: str, names: dict[str, str]) -> None:
        self._srv = server
        self._ns = ns
        self._names = names

    def __getattr__(self, name: str) -> Callable[..., Awaitable[Any]]:
        op = self._names.get(name)
        if op is None or name.startswith("_"):
            raise AttributeError(f"no operation {self._ns}.{name}")
        return _method(self._srv, op)

    def __dir__(self) -> list[str]:
        return sorted(self._names)


def _method(server: Server, op: str) -> Callable[..., Awaitable[Any]]:
    async def call(**params: Any) -> Any:
        return await server._call(op, params)

    call.__qualname__ = call.__name__ = op
    return call
